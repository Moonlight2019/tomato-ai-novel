def get_chapter_opening_instruction(chapter_num: int) -> str:
    """
    根据章节号生成开头指令。
    使用章节号作为种子，确保每章不同但可复现。
    """
    # 用章节号作为种子，保证每次生成同一章时用同一种手法
    rng = random.Random(chapter_num * 31 + 42)

    # 随机选择一种环境描写手法
    tech = rng.choice(ENVIRONMENT_TECHNIQUES)

    # 每3章左右跳过环境描写，用其他开头方式
    if chapter_num % 3 == 0:
        style = rng.choice(OPENING_STYLES)
        return f"""【开头要求】
{style['instruction']}
如果需要环境描写，使用「{tech['name']}」手法：
{tech['instruction']}
示例：{tech['example']}"""
    else:
        return f"""【环境描写要求】
使用「{tech['name']}」手法：
{tech['instruction']}
示例：{tech['example']}
注意：不要用"老旧的电风扇""黏腻的空气""昏黄的灯光"等常见AI模板句。"""


def get_description_diversity_prompt(chapter_num: int) -> str:
    """
    获取描写多样性提示，注入到章节生成 prompt 中。
    """
    instruction = get_chapter_opening_instruction(chapter_num)

    return f"""
{instruction}

【描写多样性通用要求】
1. 禁止以下AI高频开头模板：
   - "老旧的电风扇"、"黏腻的空气"、"昏黄的灯光"
   - "XX的XX在XX中XX"（四段式描写）
   - "阳光透过XX洒在XX上"
   - "空气中弥漫着XX的味道"
2. 每章开头必须与前两章不同：如果上一章用视觉开头，这章用听觉或动作
3. 环境描写不超过3句，快速切入人物/事件
4. 用具体细节替代概括性描写：写"手机屏幕裂了"不写"破旧的手机"
"""
